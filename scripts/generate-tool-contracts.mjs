import { readFile, writeFile, mkdtemp, rm } from "node:fs/promises"
import { spawnSync } from "node:child_process"
import { tmpdir } from "node:os"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const manifestPath = resolve(root, "contracts/ai-tools/v1.json")
const manifestText = await readFile(manifestPath, "utf8")
const manifest = JSON.parse(manifestText)

if (manifest.version !== 1 || !Array.isArray(manifest.tools)) throw new Error("invalid tool manifest")
const names = new Set()
for (const tool of manifest.tools) {
  if (!tool.name || names.has(tool.name)) throw new Error(`invalid or duplicate tool name: ${tool.name}`)
  names.add(tool.name)
  if (!tool.description || tool.parameters?.type !== "object") throw new Error(`invalid tool contract: ${tool.name}`)
  if (!['account', 'project'].includes(tool.scope)) throw new Error(`invalid scope: ${tool.name}`)
  if (!['read', 'write', 'destructive'].includes(tool.mutation)) throw new Error(`invalid mutation: ${tool.name}`)
}

const ts = `// Code generated by scripts/generate-tool-contracts.mjs; DO NOT EDIT.\n` +
`import type { ToolSpec } from "@/lib/ai/providers"\n\n` +
`export const SHARED_TOOL_CONTRACT_VERSION = ${manifest.version}\n` +
`export const SHARED_TOOL_CONTRACTS: Record<string, ToolSpec> = ${JSON.stringify(Object.fromEntries(manifest.tools.map(({name, description, parameters}) => [name, {name, description, parameters}])), null, 2)}\n\n` +
`export function sharedToolSpec(name: string): ToolSpec {\n  const spec = SHARED_TOOL_CONTRACTS[name]\n  if (!spec) throw new Error(\`Unknown shared tool contract: \${name}\`)\n  return spec\n}\n`

const goJSON = JSON.stringify(manifest)
const go = `// Code generated by scripts/generate-tool-contracts.mjs; DO NOT EDIT.\npackage toolcontracts\n\nimport (\n\t"encoding/json"\n\t"fmt"\n)\n\nconst manifestJSON = ${JSON.stringify(goJSON)}\n\ntype Contract struct {\n\tName string \`json:"name"\`\n\tDescription string \`json:"description"\`\n\tParameters map[string]any \`json:"parameters"\`\n\tScope string \`json:"scope"\`\n\tMutation string \`json:"mutation"\`\n\tSurfaces []string \`json:"surfaces"\`\n}\n\ntype Manifest struct {\n\tVersion int \`json:"version"\`\n\tTools []Contract \`json:"tools"\`\n}\n\nvar Shared = mustLoad()\n\nfunc mustLoad() map[string]Contract {\n\tvar manifest Manifest\n\tif err := json.Unmarshal([]byte(manifestJSON), &manifest); err != nil { panic(err) }\n\tout := make(map[string]Contract, len(manifest.Tools))\n\tfor _, tool := range manifest.Tools { out[tool.Name] = tool }\n\treturn out\n}\n\nfunc Get(name string) (Contract, error) {\n\ttool, ok := Shared[name]\n\tif !ok { return Contract{}, fmt.Errorf("unknown shared tool contract %q", name) }\n\treturn tool, nil\n}\n`
// Feeding stdin to a synchronous child can hang under PTY-based task runners.
// Formatting a temporary file works in terminals, CI, and editor agents alike.
const formatDir = await mkdtemp(resolve(tmpdir(), "inkwell-tool-contracts-"))
const formatPath = resolve(formatDir, "contracts_gen.go")
await writeFile(formatPath, go)
const gofmt = spawnSync("gofmt", ["-w", formatPath], { encoding: "utf8" })
if (gofmt.status !== 0) throw new Error(gofmt.stderr || "gofmt failed")
const formattedGo = await readFile(formatPath, "utf8")
await rm(formatDir, { recursive: true, force: true })

const outputs = [
  [resolve(root, "client/lib/ai/tool-contracts.generated.ts"), ts],
  [resolve(root, "server/internal/gateway/toolcontracts/contracts_gen.go"), formattedGo],
]
let stale = false
for (const [path, content] of outputs) {
  if (process.argv.includes("--check")) {
    const current = await readFile(path, "utf8").catch(() => "")
    if (current !== content) { console.error(`${path} is stale; run node scripts/generate-tool-contracts.mjs`); stale = true }
  } else {
    await writeFile(path, content)
  }
}
if (stale) process.exit(1)
